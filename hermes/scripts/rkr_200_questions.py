def parse_sse_events(raw_bytes):
    events = {}
    text = raw_bytes.decode('utf-8', errors='replace')
    current_event = None
    for line in text.split('\n'):
        if line.startswith('event:'):
            current_event = line[6:].strip()
        elif line.startswith('data:'):
            data_str = line[5:].strip()
            try:
                data = json.loads(data_str)
                if current_event and current_event not in events:
                    events[current_event] = []
                if current_event:
                    events[current_event].append(data)
            except:
                pass
    return events

def chat(token, message, project_id=None):
    payload = {"message": message, "stream": True}
    if project_id:
        payload["project_id"] = project_id
    chat_data = json.dumps(payload).encode()
    chat_req = urllib.request.Request(
        "http://localhost:8000/api/v1/hermes/chat",
        data=chat_data,
        headers={
            "Content-Type": "application/json",
            "Authorization": "Bearer " + token
        }
    )
    raw = urllib.request.urlopen(chat_req, timeout=120).read()
    events = parse_sse_events(raw)
    answer = ""
    for ans_event in events.get("answer", []):
        answer += ans_event.get("content", "")
    return answer, events

